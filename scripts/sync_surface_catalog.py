#!/usr/bin/env python3
"""Publish `shauron/catalog` into the platform as `surface_catalog.json`.

The platform owns the composition of a scan: it resolves a profile into steps and
freezes that plan into the ticket. So it needs the catalog at import time — and it
needs it to be the one that shipped with the CLI, not a hand-edited copy.

`inherits` is resolved here, on purpose: the platform reads a flat list of stages,
and a profile that says "like the basic one, plus these" is a convenience for the
catalogue, not a graph the resolver should have to walk.

    python scripts/sync_surface_catalog.py            # rewrite the published copy
    python scripts/sync_surface_catalog.py --check    # fail if it is out of date
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]

#: Profiles the CLI ships that this platform deliberately does not offer.
#: `test_no_profile_hunts_a_vulnerability` says a web/recon profile never carries
#: a vulnerability engine — that is the product's boundary, not a preference. An
#: organisation may still write one as a custom workflow (its own grant, its own
#: audit trail); a profile that ships it makes every tenant a scanner.
WITHHELD = {"web.hunt", "web.sqli", "web.xss"}
SOURCE = REPO.parent / "shauron" / "shauron" / "catalog"
TARGET = REPO / "backend" / "src" / "backend" / "app" / "surface_catalog.json"


def _engine_rules() -> dict:
    """The engine's own constants, not a paraphrase of them.

    A custom workflow is validated by the platform and executed by the CLI, so
    both have to agree on what a level may carry and which kinds exist. Importing
    `shauron/catalog/__init__.py` by path keeps the published rules identical to
    the ones the loader enforces — a copy here would drift the first time a level
    is added.
    """
    spec = importlib.util.spec_from_file_location("_shauron_catalog_rules",
                                                  SOURCE / "__init__.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return {
        "levels": module.LEVELS,
        "level_rank": module.LEVEL_RANK,
        "level_capabilities": {name: sorted(caps)
                               for name, caps in module.LEVEL_CAPABILITIES.items()},
        "planes": module.PLANES,
        "capabilities": module.CAPABILITIES,
        "target_kinds": module.TARGET_KINDS,
        "gates": sorted(module.GATES),
    }


def _read(directory: Path) -> dict[str, dict]:
    rows: dict[str, dict] = {}
    for path in sorted(directory.glob("*.json")):
        data = json.loads(path.read_text())
        rows[data["name"]] = data
    return rows


def _resolve(name: str, profiles: dict[str, dict], seen: tuple[str, ...] = ()) -> list[dict]:
    """Stages of a profile, its parent's first. A stage id declared twice is
    replaced by the child: that is how a profile narrows a step it inherits."""
    if name in seen:
        raise SystemExit(f"catalog: {name} inherits itself ({' -> '.join(seen + (name,))})")
    profile = profiles.get(name)
    if profile is None:
        raise SystemExit(f"catalog: {seen[-1] if seen else 'profile'} inherits unknown {name!r}")
    stages: dict[str, dict] = {}
    parent = profile.get("inherits")
    if parent:
        for stage in _resolve(parent, profiles, seen + (name,)):
            stages[stage["id"]] = stage
    for stage in profile.get("stages", []):
        stages[stage["id"]] = stage
    return list(stages.values())


def build() -> dict:
    tools = _read(SOURCE / "tools")
    profiles = _read(SOURCE / "profiles")
    published_profiles = {}
    for name, profile in profiles.items():
        if name in WITHHELD:
            continue
        published_profiles[name] = {
            "name": name,
            "label": profile.get("label", name),
            "question": profile.get("question", ""),
            "target_kind": profile.get("target_kind", "domain"),
            "level": profile.get("level"),
            "plane": profile.get("plane", ["cli", "cloud"]),
            "stages": _resolve(name, profiles),
            "limits": profile.get("limits", {}),
        }
    # The platform recomputes this over exactly these two documents, in this
    # order, so the published hash and the verified one can never disagree.
    digest = hashlib.sha256(
        (json.dumps(tools, sort_keys=True)
         + json.dumps(published_profiles, sort_keys=True)).encode()
    ).hexdigest()
    return {
        "_note": ("Published copy of shauron/catalog, generated by "
                  "scripts/sync_surface_catalog.py. The platform owns the profile and "
                  "resolves the plan; the CLI never composes one."),
        "catalog_sha256": digest,
        "source": "shauron/catalog",
        "rules": _engine_rules(),
        "profiles": published_profiles,
        "tools": tools,
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="verify the published copy matches the source")
    args = parser.parse_args()
    catalog = build()
    text = json.dumps(catalog, indent=2, sort_keys=True) + "\n"
    if args.check:
        current = TARGET.read_text() if TARGET.exists() else ""
        if current != text:
            print("surface_catalog.json is stale — run scripts/sync_surface_catalog.py")
            return 1
        print("surface_catalog.json is up to date")
        return 0
    TARGET.write_text(text)
    print(f"published {len(catalog['profiles'])} profiles, "
          f"{len(catalog['tools'])} tools, "
          f"{len(catalog['rules']['levels'])} levels -> {TARGET.relative_to(REPO)}")
    if WITHHELD:
        print(f"withheld (vulnerability hunters, the platform boundary): "
              f"{', '.join(sorted(WITHHELD))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
